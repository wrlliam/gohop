import Link from "next/link";
import { headers } from "next/headers";
import { redirect } from "next/navigation";
import {
  ClockIcon,
  CoinsIcon,
  TrendUpIcon,
  WalletIcon,
} from "@phosphor-icons/react/ssr";

import { auth } from "~/server/better-auth";
import { syncPayoutAccount } from "~/server/stripe";
import {
  getBalances,
  getEstimate,
  getLinkEarnings,
  getPayoutAccount,
  getPayouts,
  getSettings,
} from "~/server/monitisation/queries";
import {
  openStripeDashboard,
  startStripeOnboarding,
} from "~/server/actions/monetisation";
import { formatDateTime, formatNumber } from "~/lib/analytics";
import { formatBps, formatMoney } from "~/lib/money";

import { Badge } from "~/components/ui/badge";
import { Button } from "~/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "~/components/ui/card";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "~/components/ui/table";
import { StatCard } from "~/components/Analytics/AdditionalParts";
import {
  LinkMonetisationSwitch,
  WithdrawButton,
} from "~/components/Monetisation/MonetisationActions";

export default async function MonetisationPage({
  searchParams,
}: {
  searchParams: Promise<{ stripe?: string }>;
}) {
  const session = await auth.api.getSession({ headers: await headers() });
  if (!session) redirect("/login");
  const userId = session.user.id;

  const { stripe: stripeParam } = await searchParams;

  // Coming back from Stripe onboarding: refresh status immediately instead of
  // waiting for the webhook.
  let account = await getPayoutAccount(userId);
  if (account && stripeParam === "return") {
    await syncPayoutAccount(account.stripeAccountId);
    account = await getPayoutAccount(userId);
  }

  const settings = await getSettings();
  const [balances, estimate, links, payouts] = await Promise.all([
    getBalances(userId),
    getEstimate(userId, settings.platformFeeBps),
    getLinkEarnings(userId),
    getPayouts(userId),
  ]);

  const money = (minor: number) => formatMoney(minor, settings.currency);
  const stripeReady = !!account?.payoutsEnabled;
  const minimum = Math.max(
    settings.minWithdrawalMinor,
    settings.withdrawalFeeMinor + 1,
  );
  const canWithdraw = stripeReady && balances.available >= minimum;

  const withdrawHint = !account
    ? "Connect Stripe to receive withdrawals."
    : !stripeReady
      ? "Finish your Stripe setup to enable withdrawals."
      : balances.available < minimum
        ? `Minimum withdrawal is ${money(minimum)}.`
        : `You'll receive ${money(balances.available - settings.withdrawalFeeMinor)} after the ${money(settings.withdrawalFeeMinor)} withdrawal fee.`;

  return (
    <main className="flex-1 space-y-8 p-6 lg:p-8">
      <div className="space-y-1">
        <h1 className="text-3xl font-bold tracking-tight">Monetisation</h1>
        <p className="text-muted-foreground max-w-2xl text-sm">
          You earn a share of the ad revenue generated by genuine, unique views
          on your links. goHop keeps {formatBps(settings.platformFeeBps)} of
          that revenue. Earnings are calculated at the end of each period and
          become withdrawable {settings.holdDays} days later.
        </p>
      </div>

      {/* KPIs */}
      <div className="grid gap-4 md:grid-cols-2 lg:grid-cols-4">
        <StatCard
          label="Available"
          icon={WalletIcon}
          value={money(balances.available)}
          hint="Ready to withdraw"
        />
        <StatCard
          label="Pending"
          icon={ClockIcon}
          value={money(balances.pending)}
          hint={`Unlocks ${settings.holdDays} days after each period closes`}
        />
        <StatCard
          label="Lifetime earned"
          icon={CoinsIcon}
          value={money(balances.lifetime)}
          hint="After platform fee"
        />
        <StatCard
          label="This period (estimate)"
          icon={TrendUpIcon}
          value={estimate ? money(estimate.minor) : "—"}
          hint={
            estimate
              ? `${formatNumber(estimate.views)} billable views so far. Final figure may differ.`
              : "Available after your first period closes"
          }
        />
      </div>

      {/* Withdraw + Stripe */}
      <Card>
        <CardHeader>
          <CardTitle>Withdraw</CardTitle>
          <CardDescription>
            Payments are sent through Stripe to the bank account you set up
            there.
          </CardDescription>
        </CardHeader>
        <CardContent className="flex flex-wrap items-center gap-3">
          {!stripeReady ? (
            <form action={startStripeOnboarding}>
              <Button type="submit">
                {account ? "Continue Stripe setup" : "Connect Stripe"}
              </Button>
            </form>
          ) : (
            <>
              <WithdrawButton
                disabled={!canWithdraw}
                label={`Withdraw ${money(balances.available)}`}
              />
              <form action={openStripeDashboard}>
                <Button type="submit" variant="outline">
                  Stripe dashboard
                </Button>
              </form>
            </>
          )}
          <Badge variant={stripeReady ? "default" : "outline"}>
            {stripeReady
              ? "Stripe connected"
              : account
                ? "Setup incomplete"
                : "Not connected"}
          </Badge>
          <p className="text-muted-foreground w-full text-sm">{withdrawHint}</p>
        </CardContent>
      </Card>

      {/* Per-link earnings */}
      <Card>
        <CardHeader>
          <CardTitle>Earnings by link</CardTitle>
          <CardDescription>
            Highest earners first. Turn a link off to stop ads and earnings on
            it; views already counted stay counted.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Link</TableHead>
                <TableHead>Status</TableHead>
                <TableHead className="text-right">Billable views</TableHead>
                <TableHead className="text-right">Earned</TableHead>
                <TableHead className="text-right">Monetised</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {links.length === 0 && (
                <TableRow>
                  <TableCell
                    colSpan={5}
                    className="text-muted-foreground py-10 text-center"
                  >
                    You haven&apos;t created any links yet.
                  </TableCell>
                </TableRow>
              )}
              {links.map((l) => (
                <TableRow key={l.id}>
                  <TableCell>
                    <Link
                      href={`/app/analytics/${l.code}`}
                      className="font-medium hover:underline"
                    >
                      {l.name ?? "Untitled link"}
                    </Link>
                    <p className="text-muted-foreground font-mono text-xs">
                      /~/{l.code}
                    </p>
                  </TableCell>
                  <TableCell>
                    {!l.isActive ? (
                      <Badge variant="outline">Inactive</Badge>
                    ) : l.monetisationEnabled ? (
                      <Badge>Earning</Badge>
                    ) : (
                      <Badge variant="secondary">Blocked</Badge>
                    )}
                  </TableCell>
                  <TableCell className="text-right tabular-nums">
                    {formatNumber(l.billableViews)}
                  </TableCell>
                  <TableCell className="text-right font-medium tabular-nums">
                    {money(l.earnedMinor)}
                  </TableCell>
                  <TableCell className="text-right">
                    <LinkMonetisationSwitch
                      linkId={l.id}
                      enabled={l.monetisationEnabled}
                      label={`Monetisation for ${l.name ?? l.code}`}
                    />
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      {/* Payout history */}
      <Card>
        <CardHeader>
          <CardTitle>Withdrawal history</CardTitle>
        </CardHeader>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Date</TableHead>
                <TableHead className="text-right">Received</TableHead>
                <TableHead className="text-right">Fee</TableHead>
                <TableHead>Status</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {payouts.length === 0 && (
                <TableRow>
                  <TableCell
                    colSpan={4}
                    className="text-muted-foreground py-10 text-center"
                  >
                    No withdrawals yet.
                  </TableCell>
                </TableRow>
              )}
              {payouts.map((p) => (
                <TableRow key={p.id}>
                  <TableCell className="whitespace-nowrap">
                    {formatDateTime(p.createdAt)}
                  </TableCell>
                  <TableCell className="text-right tabular-nums">
                    {formatMoney(p.amountMinor, p.currency)}
                  </TableCell>
                  <TableCell className="text-muted-foreground text-right tabular-nums">
                    {formatMoney(p.feeMinor, p.currency)}
                  </TableCell>
                  <TableCell>
                    <Badge
                      variant={
                        p.status === "sent"
                          ? "default"
                          : p.status === "failed"
                            ? "outline"
                            : "secondary"
                      }
                    >
                      {p.status === "sent"
                        ? "Sent"
                        : p.status === "failed"
                          ? "Failed"
                          : "Processing"}
                    </Badge>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>
    </main>
  );
}
